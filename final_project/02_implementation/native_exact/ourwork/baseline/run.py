"""Persistent sequential MOTPE runner; proposals stay in the owning process.

Candidate evaluation uses a subprocess for a hard wall-clock bound and memory cleanup.
The same concrete-configuration job interface is intended for later evolutionary arms.
"""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import pickle
import subprocess
import sys
import time
from .adapter import configure, grounding_manifest, prepare, question_manifest, resolve_sources
from .records import RunStore, append_jsonl, atomic_json, environment, fingerprint, source_identity
from .spec import capability_overrides, load_protocol


def save_sampler(path, sampler):
    data = pickle.dumps(sampler)
    sha = hashlib.sha256(data).hexdigest()
    target = path / f'sampler-{sha}.pkl'
    if not target.exists():
        with target.open('wb') as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
    atomic_json(path / 'sampler_checkpoint.json', {'file': target.name, 'sha256': sha})


def restore_sampler(path):
    info = json.loads((path / 'sampler_checkpoint.json').read_text())
    file = path / info['file']
    if file.parent != path or file.name != f'sampler-{info["sha256"]}.pkl':
        raise ValueError('Invalid sampler checkpoint path')
    raw = file.read_bytes()
    if hashlib.sha256(raw).hexdigest() != info['sha256']:
        raise ValueError('Sampler checkpoint hash mismatch')
    # Only restore artifacts generated by this runner, never third-party pickle files.
    return pickle.loads(raw)


def execute_job(job, timeout, root):
    path = Path(job['destination'])
    path.mkdir(parents=True, exist_ok=True)
    atomic_json(path / 'job.json', job)
    with (path / 'worker.log').open('a') as output:
        process = subprocess.Popen([sys.executable, '-m', 'ourwork.baseline.worker', str(path / 'job.json')],
                                   cwd=root, stdout=output, stderr=subprocess.STDOUT, start_new_session=True)
        try:
            code = process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            import signal
            os.killpg(process.pid, signal.SIGKILL)
            process.wait()
            return {'status': 'timeout', 'error': f'Candidate wall timeout after {timeout:.1f}s'}
    result = path / 'result.json'
    return json.loads(result.read_text()) if result.exists() else {
        'status': 'failed', 'error': f'Worker exited {code} without a result'}


def eligible(metrics, protocol):
    return (metrics.get('full_evaluation') and metrics.get('usage_verified')
            and metrics.get('generation_success_rate', 0) >= protocol['minimum_success_rate']
            and (protocol['objective_quality'] != 'accuracy' or
                 metrics.get('judge_success_rate', 0) >= protocol['minimum_success_rate']))


def run(args):
    import optuna
    root = Path(__file__).resolve().parents[2]
    protocol = load_protocol(args.protocol)
    if protocol['stage'] == 'confirm':
        raise ValueError('Use the confirm command with preselected candidates; holdout search is prohibited')
    destination = Path(args.output).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    lock = (destination / '.run.lock').open('a')
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    original = json.loads((Path(__file__).parent / 'resolved_sources.json').read_text())
    frozen_sources = destination / 'sources.json'
    sources = json.loads(frozen_sources.read_text()) if args.resume and frozen_sources.exists() else resolve_sources(protocol, original)
    identity = source_identity(root)
    server_metadata = json.loads(Path(args.server_metadata).read_text())
    if server_metadata['model_revision'] != sources['model']['revision']:
        raise ValueError('Server model revision differs from the pinned model')
    if server_metadata['server_revision'] != sources['llama']['revision']:
        raise ValueError('Server build revision differs from the pinned serving code')
    if server_metadata['context'] != protocol['context_window']:
        raise ValueError('Server context differs from the protocol')
    preflight = json.loads(Path(args.preflight).read_text())
    if preflight.get('status') != 'passed':
        raise ValueError('A successful server/GPU preflight is required')
    if protocol['stage'] in {'baseline', 'pilot'}:
        if not args.capabilities_run:
            raise ValueError('A passing --capabilities-run is required before research studies')
        capability_root = Path(args.capabilities_run)
        capability_protocol = json.loads((capability_root / 'protocol.json').read_text())
        from .spec import search_spec
        if capability_protocol['experiment'].get('embedding_device', 'cpu') != protocol.get('embedding_device', 'cpu'):
            raise ValueError('Capability run used a different embedding device policy')
        if search_spec(capability_protocol['experiment']) != search_spec(protocol):
            raise ValueError('Capability run tested a different search space')
        if capability_protocol['sources'] != sources or capability_protocol['source_identity'] != identity:
            raise ValueError('Capability run used different code/model/data revisions')
        capability_summary = json.loads((capability_root / 'analysis/summary.json').read_text())
        if (len(capability_summary['capability_results']) != len(capability_overrides()) or
                any(v != 'COMPLETE' for v in capability_summary['capability_results'].values())):
            raise ValueError('All representative workflow/module capability checks must pass')
        embedding_checks = json.loads((capability_root / 'embedding_checks.json').read_text())
        if any(embedding_checks.get(name, {}).get('status') != 'passed' for name in protocol['embedding_models']):
            raise ValueError('An embedding in the search catalog has not passed its local load test')
    immutable = {'experiment': protocol, 'optimizer_seed': args.seed,
                 'source_identity': identity, 'sources': sources, 'server': server_metadata}
    store = RunStore(destination, immutable, resume=args.resume)
    atomic_json(frozen_sources, sources)
    hardware = environment()
    atomic_json(destination / f'environment-{time.time_ns()}.json', hardware)
    gpu_rows = hardware.get('gpu', {}).get('stdout', '').splitlines()[1:]
    hardware_class = [[part.strip() for i, part in enumerate(row.split(',')) if i != 1]
                      for row in gpu_rows if row.strip()]  # UUID differs by allocation; device class must not.
    hardware_path = destination / 'hardware_class.json'
    if args.resume and hardware_path.exists() and json.loads(hardware_path.read_text()) != hardware_class:
        raise ValueError('GPU class/memory/driver changed; do not mix timing blocks on resume')
    atomic_json(hardware_path, hardware_class)
    workspace = Path(args.workspace).resolve()
    study_config, _builder, _hf = prepare(protocol, workspace, sources)
    if protocol['stage'] == 'capabilities':
        check_path = destination / 'embedding_checks.json'
        checks = json.loads(check_path.read_text()) if args.resume and check_path.exists() else {}
        for model_name in protocol['embedding_models']:
            if checks.get(model_name, {}).get('status') == 'passed':
                continue
            try:
                embedding = _hf.get_hf_embedding_model(model_name, timeout_config=study_config.timeouts, device='cpu')
                vector = embedding.get_text_embedding('Baseline embedding capability check.')
                if not vector or not all(__import__('math').isfinite(v) for v in vector):
                    raise ValueError('Invalid embedding vector')
                checks[model_name] = {'status': 'passed', 'dimensions': len(vector),
                                      'embedding_device': protocol.get('embedding_device', 'cpu')}
                del embedding
                __import__('gc').collect()
                if protocol.get('embedding_device') == 'cuda:1':
                    __import__('torch').cuda.empty_cache()
            except Exception as e:
                checks[model_name] = {'status': 'failed', 'error': f'{type(e).__name__}: {e}'}
            atomic_json(check_path, checks)
    pairs, qa_manifest = question_manifest(study_config, protocol)
    manifest_path = destination / 'questions_manifest.json'
    if manifest_path.exists() and json.loads(manifest_path.read_text()) != qa_manifest:
        raise ValueError('Question manifest changed on resume')
    atomic_json(manifest_path, qa_manifest)
    grounding = grounding_manifest(study_config)
    gp = destination / 'grounding_manifest.json'
    if gp.exists() and json.loads(gp.read_text()) != grounding:
        raise ValueError('Grounding corpus changed on resume')
    atomic_json(gp, grounding)
    atomic_json(destination / 'effective_study.json', study_config.model_dump(mode='json'))
    space = study_config.search_space
    atomic_json(destination / 'distributions.json',
                {k: optuna.distributions.distribution_to_json(v) for k, v in space.build_distributions().items()})
    # Persist exact package/sampler behavior; a resume cannot silently change numerical libraries.
    versions = hardware['packages']
    vp = destination / 'packages.json'
    if args.resume and vp.exists() and json.loads(vp.read_text()) != versions:
        raise ValueError('Package versions changed; restore the original environment before resuming')
    atomic_json(vp, versions)
    if args.resume:
        sampler = restore_sampler(destination)
    else:
        sampler = optuna.samplers.TPESampler(seed=args.seed, n_startup_trials=protocol['startup_trials'],
                                             multivariate=True, constant_liar=True)
    study = optuna.create_study(study_name='baseline',
                                storage=f'sqlite:///{destination / "study.sqlite3"}',
                                sampler=sampler, directions=['maximize', 'minimize'], load_if_exists=args.resume)
    # Interrupted attempts consume budget; never treat partial results as full objectives.
    for old in study.get_trials(states=(optuna.trial.TrialState.RUNNING,)):
        study.tell(old.number, state=optuna.trial.TrialState.FAIL)
        store.event('interrupted_candidate', trial_number=old.number)
    cases = capability_overrides()
    if protocol['stage'] == 'capabilities' and protocol['budget'] != len(cases):
        raise ValueError(f'Capabilities budget must be {len(cases)}')
    if not args.resume:
        if protocol['stage'] == 'capabilities':
            for name, params in cases:
                study.enqueue_trial({**params, 'rag_embedding_model': protocol['embedding_models'][0],
                                     'few_shot_embedding_model': protocol['embedding_models'][0], 'few_shot_top_k': 2},
                                    user_attrs={'capability': name})
        else:
            # Identical common initial configurations are included in the total budget.
            for name, params in cases[:min(len(protocol['rag_modes']), protocol['budget'])]:
                study.enqueue_trial({**params, 'rag_embedding_model': protocol['embedding_models'][0]},
                                    user_attrs={'initialization': name})
        save_sampler(destination, sampler)
    deadline = time.monotonic() + args.max_hours * 3600
    while len([t for t in study.trials if t.state != optuna.trial.TrialState.WAITING]) < protocol['budget']:
        if deadline - time.monotonic() < 120:
            store.event('session_budget_reached')
            break
        trial = study.ask()
        try:
            params = space.sample(trial)
            # Seed unspecified branch choices for capability runs to the small first embedding.
            candidate_id = fingerprint(params)
            trial.set_user_attr('candidate_id', candidate_id)
            trial.set_user_attr('concrete_params', params)
            # Checkpoint immediately after sampling, before expensive work.
            save_sampler(destination, sampler)
            duplicate = any(t.number != trial.number and t.user_attrs.get('candidate_id') == candidate_id
                            for t in study.get_trials() if t.state != optuna.trial.TrialState.WAITING)
            if duplicate:
                trial.set_user_attr('failure_reason', 'duplicate_candidate')
                study.tell(trial, state=optuna.trial.TrialState.FAIL)
                store.event('duplicate_candidate', trial_number=trial.number, candidate_id=candidate_id)
                continue
            job = {'protocol': protocol, 'params': params, 'sources': sources,
                   'question_manifest': qa_manifest, 'candidate_id': candidate_id,
                   'evaluation_seed': int(candidate_id[:8], 16), 'workspace': str(workspace),
                   'destination': str(destination / 'candidates' / f'{trial.number:05d}-{candidate_id[:12]}')}
            store.event('candidate_started', trial_number=trial.number, candidate_id=candidate_id, params=params)
            print(f'CANDIDATE_STARTED trial={trial.number} mode={params.get("rag_mode")} embedding={params.get("rag_embedding_model")} policy={protocol.get("embedding_device", "cpu")}', flush=True)
            wall_start = time.monotonic()
            timeout = min(protocol['candidate_timeout'], deadline - wall_start - 60)
            result = execute_job(job, timeout, root)
            print(f'CANDIDATE_FINISHED trial={trial.number} status={result.get("status")} wall_seconds={time.monotonic()-wall_start:.1f}', flush=True)
            trial.set_user_attr('wall_seconds', time.monotonic() - wall_start)
            trial.set_user_attr('result_path', str(Path(job['destination']).relative_to(destination)))
            metrics = result.get('metrics', {})
            trial.set_user_attr('metrics', metrics)
            if result['status'] == 'evaluated' and eligible(metrics, protocol):
                study.tell(trial, [metrics[protocol['objective_quality']], metrics[protocol['objective_resource']]])
            else:
                trial.set_user_attr('failure_reason', result.get('error', 'measurement_or_success_gate'))
                study.tell(trial, state=optuna.trial.TrialState.FAIL)
            store.event('candidate_finished', trial_number=trial.number, result=result)
        except BaseException as e:
            if study.trials[trial.number].state == optuna.trial.TrialState.RUNNING:
                study.tell(trial, state=optuna.trial.TrialState.FAIL)
            store.event('candidate_exception', trial_number=trial.number, error=f'{type(e).__name__}: {e}')
            if isinstance(e, (KeyboardInterrupt, SystemExit)):
                raise
        finally:
            save_sampler(destination, sampler)
            from .analyze import analyze
            analyze(destination)
    store.event('session_finished', trials=len(study.trials))
    from .analyze import analyze
    analyze(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--protocol', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--workspace', required=True)
    parser.add_argument('--server-metadata', required=True)
    parser.add_argument('--preflight', required=True)
    parser.add_argument('--capabilities-run')
    parser.add_argument('--seed', type=int, default=11)
    parser.add_argument('--max-hours', type=float, default=9)
    parser.add_argument('--resume', action='store_true')
    args = parser.parse_args()
    if args.max_hours <= 0:
        parser.error('--max-hours must be positive')
    run(args)


if __name__ == '__main__':
    main()
